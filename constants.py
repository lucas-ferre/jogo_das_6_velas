def get_target_victory_turns(persona_id, difficulty):
    if difficulty == DIFFICULTY_ENDLESS:
        return None
    base_turns = {
        PERSONA_CARETAKER: 75,
        PERSONA_OCCULTIST: 65,
        PERSONA_WANDERER: 70,
        PERSONA_PALADIN: 80,
        PERSONA_MOONBORN: 60
    }
    base = base_turns.get(persona_id, 70)
    if difficulty == DIFFICULTY_EASY:
        return max(20, base - 10)
    elif difficulty == DIFFICULTY_HARD:
        return base + 15
    return base

